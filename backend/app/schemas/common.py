"""Pydantic v2 response schemas matching frontend contracts exactly."""
from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any, Generic, Literal, TypeVar

from pydantic import BaseModel, ConfigDict, Field

T = TypeVar("T")

SCHEMA_VERSION = "1.0"


# ?? Envelope ?????????????????????????????????????????????????????????????????

class Meta(BaseModel):
    request_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    schema_version: Literal["1.0"] = SCHEMA_VERSION


class ApiResponse(BaseModel, Generic[T]):
    data: T
    meta: Meta = Field(default_factory=Meta)


class ApiErrorBody(BaseModel):
    code: str
    message: str
    details: dict[str, Any] = Field(default_factory=dict)


class ApiErrorResponse(BaseModel):
    error: ApiErrorBody
    meta: Meta = Field(default_factory=Meta)


# ?? Common ????????????????????????????????????????????????????????????????????

class Paginated(BaseModel, Generic[T]):
    items: list[T]
    next_cursor: str | None = None
    total: int


# ?? Health ????????????????????????????????????????????????????????????????????

class HealthOut(BaseModel):
    status: Literal["ok", "degraded"]
    version: str


# ?? Application ???????????????????????????????????????????????????????????????

class ApplicationOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: str
    name: str
    description: str
    workspace_key: str
    repository_revision: str
    monitoring_enabled: bool
    status: str
    supported_errors: list[str]


# ?? Incidents ?????????????????????????????????????????????????????????????????

class IncidentOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: str
    application_id: str
    source_event_id: str
    fingerprint: str
    severity: str
    error_type: str
    message: str
    status: str
    current_stage: str
    repository_revision: str
    active_run_id: str | None
    detected_at: datetime
    resolved_at: datetime | None


class IncidentCreate(BaseModel):
    application_id: str
    source_event_id: str
    fingerprint: str
    severity: str = "medium"
    error_type: str
    message: str
    source_log: str = ""
    repository_revision: str = "HEAD"


# ?? Diagnosis ?????????????????????????????????????????????????????????????????

class EvidenceOut(BaseModel):
    file_path: str
    symbol: str
    start_line: int
    end_line: int
    repository_revision: str
    artifact_id: str
    excerpt: str


class DiagnosisOut(BaseModel):
    incident_id: str
    run_id: str
    status: Literal["completed", "manual_review"]
    hypothesis: str
    confidence_label: Literal["low", "medium", "high"]
    uncertainty: str
    suggested_direction: str
    evidence: list[EvidenceOut]


# ?? Patches ???????????????????????????????????????????????????????????????????

class PatchOut(BaseModel):
    id: str
    incident_id: str
    run_id: str
    version: int
    base_revision: str
    patch_hash: str
    changed_files: list[str]
    rationale: str
    diff_artifact_id: str
    status: str
    diff: str


# ?? Validation ????????????????????????????????????????????????????????????????

class CheckOut(BaseModel):
    name: str
    status: str
    exit_code: int | None
    duration_ms: int
    evidence_artifact_id: str
    evidence: str


class ValidationOut(BaseModel):
    candidate_id: str
    patch_hash: str
    status: str
    checks: list[CheckOut]
    environment_id: str
    duration_ms: int


# ?? Approval ??????????????????????????????????????????????????????????????????

class ApprovalRequest(BaseModel):
    candidate_id: str
    patch_hash: str
    base_revision: str
    decision: Literal["approve", "reject"]
    comment: str | None = None


class ApplyRequest(BaseModel):
    candidate_id: str
    patch_hash: str
    base_revision: str


class DecisionOut(BaseModel):
    id: str
    incident_id: str
    candidate_id: str
    patch_hash: str
    base_revision: str
    decision: str
    actor_id: str
    comment: str | None
    decided_at: datetime


# ?? Application Attempt ???????????????????????????????????????????????????????

class AttemptOut(BaseModel):
    id: str
    candidate_id: str
    snapshot_ref: str
    before_revision: str
    after_revision: str | None
    status: str
    applied_at: datetime
    restore_status: str


# ?? Verification ??????????????????????????????????????????????????????????????

class VerificationOut(BaseModel):
    id: str
    application_attempt_id: str
    candidate_id: str
    status: str
    checks: list[CheckOut]
    monitoring_observation: str
    evidence_artifact_id: str


# ?? Incident Detail ???????????????????????????????????????????????????????????

class IncidentDetailOut(IncidentOut):
    source_log: str
    diagnosis: DiagnosisOut | None
    patches: list[PatchOut]
    validation: ValidationOut | None
    decision: DecisionOut | None
    application_attempt: AttemptOut | None
    verification: VerificationOut | None
    report: ReportOut | None
    can_approve: bool
    can_reject: bool
    can_apply: bool
    permission_reason: str


# ?? Events ????????????????????????????????????????????????????????????????????

class EventOut(BaseModel):
    id: str
    incident_id: str
    run_id: str | None
    event_type: str
    actor_type: str
    actor_id: str
    payload: dict[str, Any]
    occurred_at: datetime


# ?? Agents ????????????????????????????????????????????????????????????????????

class ExecutionOut(BaseModel):
    schema_version: Literal["1.0"] = "1.0"
    incident_id: str
    run_id: str
    stage: str
    agent_type: str
    status: str
    created_at: datetime
    input_revision: str
    error: str | None


class AgentSummaryOut(BaseModel):
    agent_type: str
    name: str
    status: str
    responsibility: str
    owner: str
    current_task: str | None
    last_activity: str | None


class AgentDetailOut(AgentSummaryOut):
    inputs: list[str]
    outputs: list[str]
    recent_runs: list[ExecutionOut]


# ?? Report ????????????????????????????????????????????????????????????????????

class ReportOut(BaseModel):
    id: str
    incident_id: str
    version: int
    outcome: str
    report_artifact_id: str
    summary: str
    limitations: list[str]
    generated_at: datetime


# ?? Dashboard ?????????????????????????????????????????????????????????????????

class DashboardSummaryOut(BaseModel):
    total_incidents: int
    open_incidents: int
    awaiting_approval: int
    resolved: int
    active_agents: int
    current_runs: int
    agent_statuses: list[AgentSummaryOut]
    last_updated: datetime


# ?? Settings ??????????????????????????????????????????????????????????????????

class SafeBackendSettings(BaseModel):
    monitoring_interval_seconds: int = Field(ge=3, le=60, default=5)
    max_candidate_revisions: int = Field(ge=0, le=2, default=2)


# ?? Filters ???????????????????????????????????????????????????????????????????

class IncidentFilters(BaseModel):
    status: str | None = None
    severity: str | None = None
    application_id: str | None = None
    cursor: str | None = None
    limit: int = Field(default=10, ge=1, le=100)
    search: str | None = None
    scope: str | None = None
    sort: str | None = None
