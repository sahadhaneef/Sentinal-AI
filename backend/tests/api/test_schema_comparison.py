"""Regression coverage for SQLite's ambiguously named composite unique constraints."""

from pathlib import Path

import pytest
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import MetaData, UniqueConstraint

from alembic import command
from app.core.config import BACKEND_ROOT, Settings
from app.db.base import Base
from app.db.session import create_database_engine


def test_semantic_unique_comparison_still_detects_a_missing_constraint(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    url = f"sqlite:///{(tmp_path / 'missing-unique.db').as_posix()}"
    monkeypatch.setenv("SENTINEL_DATABASE_URL", url)
    engine = create_database_engine(Settings(_env_file=None, database_url=url, environment="test"))
    try:
        schema = MetaData()
        for table in Base.metadata.sorted_tables:
            table.to_metadata(schema)
        users = schema.tables["users"]
        for constraint in list(users.constraints):
            if isinstance(constraint, UniqueConstraint) and set(constraint.columns.keys()) == {
                "username"
            }:
                users.constraints.remove(constraint)
        schema.create_all(engine)
        config = Config(str(BACKEND_ROOT / "alembic.ini"))
        command.stamp(config, "head")
        with pytest.raises(AutogenerateDiffsDetected) as failure:
            command.check(config)
        assert any(
            operation[0] == "add_constraint" and operation[1].table.name == "users"
            for operation in failure.value.diffs
        )
    finally:
        engine.dispose()
